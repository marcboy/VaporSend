import pako from 'pako';

const BASE45_CHARSET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ $%*+-./:";
const BASE64_CHARSET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=";

const BASE45_MAP = {};
for (let i = 0; i < BASE45_CHARSET.length; i++) BASE45_MAP[BASE45_CHARSET[i]] = i;

const BASE64_MAP = {};
for (let i = 0; i < BASE64_CHARSET.length; i++) BASE64_MAP[BASE64_CHARSET[i]] = i;

/**
 * Encodes a Uint8Array into a Base45 string (RFC 9285).
 */
export function uint8ArrayToBase45(uint8Array) {
  let result = "";
  const len = uint8Array.length;
  for (let i = 0; i < len; i += 2) {
    if (i + 1 < len) {
      const val = (uint8Array[i] << 8) + uint8Array[i + 1];
      const c1 = val % 45;
      const c2 = Math.floor(val / 45) % 45;
      const c3 = Math.floor(val / (45 * 45)) % 45;
      result += BASE45_CHARSET[c1] + BASE45_CHARSET[c2] + BASE45_CHARSET[c3];
    } else {
      const val = uint8Array[i];
      const c1 = val % 45;
      const c2 = Math.floor(val / 45) % 45;
      result += BASE45_CHARSET[c1] + BASE45_CHARSET[c2];
    }
  }
  return result;
}

/**
 * Decodes a Base45 string into a Uint8Array (RFC 9285).
 */
export function base45ToUint8Array(base45String) {
  const charToVal = {};
  for (let i = 0; i < 45; i++) {
    charToVal[BASE45_CHARSET[i]] = i;
  }
  
  const result = [];
  const len = base45String.length;
  
  for (let i = 0; i < len; i += 3) {
    if (i + 2 < len) {
      const c1 = charToVal[base45String[i]];
      const c2 = charToVal[base45String[i + 1]];
      const c3 = charToVal[base45String[i + 2]];
      
      if (c1 === undefined || c2 === undefined || c3 === undefined) {
        throw new Error("Invalid character in Base45 string");
      }
      
      const val = c1 + c2 * 45 + c3 * 45 * 45;
      result.push((val >> 8) & 0xff);
      result.push(val & 0xff);
    } else {
      const c1 = charToVal[base45String[i]];
      const c2 = charToVal[base45String[i + 1]];
      
      if (c1 === undefined || c2 === undefined) {
        throw new Error("Invalid character in Base45 string");
      }
      
      const val = c1 + c2 * 45;
      result.push(val & 0xff);
    }
  }
  
  return new Uint8Array(result);
}

/**
 * Encodes a Uint8Array into a Base64 string.
 */
export function uint8ArrayToBase64(uint8Array) {
  let binary = '';
  const len = uint8Array.byteLength;
  const chunkSize = 8192;
  for (let i = 0; i < len; i += chunkSize) {
    const chunk = uint8Array.subarray(i, i + chunkSize);
    binary += String.fromCharCode.apply(null, chunk);
  }
  return btoa(binary);
}

/**
 * Decodes a Base64 string into a Uint8Array.
 */
export function base64ToUint8Array(base64String) {
  const binaryString = atob(base64String);
  const len = binaryString.length;
  const bytes = new Uint8Array(len);
  for (let i = 0; i < len; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  return bytes;
}

/**
 * Compresses data and splits it into chunks.
 * @param {Uint8Array|string} data - The raw binary data or text string.
 * @param {string} filename - Name of the file, or '_clip_' for clipboard text.
 * @param {number} maxChunkSize - Max character length of the payload per QR code.
 * @param {string} encoding - Encoding scheme: 'base64' or 'base45'.
 * @returns {Array<string>} Array of ready-to-render QR code text payloads.
 */
export function prepareChunks(data, filename, maxChunkSize = 400, encoding = 'base45') {
  let binaryData;
  if (typeof data === 'string') {
    binaryData = new TextEncoder().encode(data);
  } else if (data instanceof ArrayBuffer) {
    binaryData = new Uint8Array(data);
  } else {
    binaryData = data;
  }

  // Compress using GZIP
  const compressed = pako.gzip(binaryData);
  const encodedContent = encoding === 'base45' 
    ? uint8ArrayToBase45(compressed) 
    : uint8ArrayToBase64(compressed);
  
  const totalLength = encodedContent.length;
  const numChunks = Math.ceil(totalLength / maxChunkSize);
  
  const sessionId = Math.floor(Math.random() * 0xffff).toString(16).toUpperCase().padStart(4, '0');
  const encodedFilename = uint8ArrayToBase45(new TextEncoder().encode(filename));
  const encCode = encoding === 'base45' ? '45' : '64';
  
  const chunks = [];
  for (let i = 0; i < numChunks; i++) {
    const start = i * maxChunkSize;
    const end = Math.min(start + maxChunkSize, totalLength);
    const slice = encodedContent.slice(start, end);
    
    // Use strictly QR Alphanumeric characters (0-9, A-Z, :) so Base45 stays in compact Alphanumeric QR mode
    const chunkText = `V1:${sessionId}:${numChunks}:${i}:${encCode}:${encodedFilename.length}:${encodedFilename}${slice}`;
    chunks.push(chunkText);
  }
  
  return chunks;
}

/**
 * Creates a Fountain / XOR-like modular parity QR chunk from a subset of original chunks.
 * @param {Array<string>} chunks - The array of V1 chunk strings generated by prepareChunks.
 * @param {Array<number>} indices - Distinct chunk indices to combine (e.g., [2, 7] or [1, 4, 9]).
 * @returns {string|null} Ready-to-render VX fountain QR payload.
 */
export function createFountainChunk(chunks, indices) {
  if (!chunks || chunks.length < 2 || !indices || indices.length < 2) return null;

  const parsedList = indices.map(idx => parseChunk(chunks[idx])).filter(Boolean);
  if (parsedList.length < 2) return null;

  const first = parsedList[0];
  const lastParsed = parseChunk(chunks[chunks.length - 1]);
  const lastChunkLen = lastParsed ? lastParsed.payload.length : first.payload.length;

  const encoding = first.encoding;
  const charset = encoding === 'base45' ? BASE45_CHARSET : BASE64_CHARSET;
  const charMap = encoding === 'base45' ? BASE45_MAP : BASE64_MAP;
  const mod = charset.length;

  const maxLen = Math.max(...parsedList.map(p => p.payload.length));
  let parityPayload = '';

  for (let pos = 0; pos < maxLen; pos++) {
    let sum = 0;
    for (let k = 0; k < parsedList.length; k++) {
      const slice = parsedList[k].payload;
      if (pos < slice.length) {
        sum += charMap[slice[pos]] || 0;
      }
    }
    parityPayload += charset[sum % mod];
  }

  const encodedFilename = uint8ArrayToBase45(new TextEncoder().encode(first.filename));
  const encCode = encoding === 'base45' ? '45' : '64';
  const indexSpec = indices.join('-');

  return `VX:${first.sessionId}:${first.total}:${indexSpec}:${lastChunkLen}:${encCode}:${encodedFilename.length}:${encodedFilename}${parityPayload}`;
}

/**
 * Recovers a single missing chunk payload from a VX fountain parity payload and the other known chunk payloads.
 */
export function recoverFountainSlice(parityPayload, knownPayloads, targetLen, encoding = 'base45') {
  const charset = encoding === 'base45' ? BASE45_CHARSET : BASE64_CHARSET;
  const charMap = encoding === 'base45' ? BASE45_MAP : BASE64_MAP;
  const mod = charset.length;

  const len = Math.min(targetLen, parityPayload.length);
  let recovered = '';

  for (let pos = 0; pos < len; pos++) {
    let val = charMap[parityPayload[pos]] || 0;
    for (let k = 0; k < knownPayloads.length; k++) {
      const kSlice = knownPayloads[k];
      if (pos < kSlice.length) {
        const kVal = charMap[kSlice[pos]] || 0;
        val = (val - kVal + mod) % mod;
      }
    }
    recovered += charset[val];
  }

  return recovered;
}

/**
 * Parses a scanned QR code chunk (supports V1 standard chunks, VX fountain repair chunks, and legacy pipe chunks).
 */
export function parseChunk(qrText) {
  if (!qrText) return null;

  // VX Fountain Repair format: VX:SESSION:TOTAL:IDX1-IDX2:LASTLEN:ENC:FNLEN:ENCODED_FILENAME_AND_PAYLOAD
  if (qrText.startsWith('VX:')) {
    const parts = qrText.split(':');
    if (parts.length < 8) return null;

    const sessionId = parts[1];
    const total = parseInt(parts[2], 10);
    const indices = parts[3].split('-').map(n => parseInt(n, 10)).filter(n => !isNaN(n));
    const lastChunkLen = parseInt(parts[4], 10);
    const encodingCode = parts[5];
    const fnLen = parseInt(parts[6], 10);
    const rest = parts.slice(7).join(':');

    if (isNaN(total) || isNaN(lastChunkLen) || isNaN(fnLen) || !sessionId || indices.length < 2 || rest.length < fnLen) {
      return null;
    }

    try {
      const encodedFilename = rest.slice(0, fnLen);
      const payload = rest.slice(fnLen);
      const filename = new TextDecoder().decode(base45ToUint8Array(encodedFilename));

      return {
        isFountain: true,
        sessionId,
        total,
        indices,
        lastChunkLen,
        filename,
        encoding: encodingCode === '45' ? 'base45' : 'base64',
        payload
      };
    } catch (e) {
      return null;
    }
  }

  // V1 Alphanumeric-optimized format: V1:SESSION:TOTAL:INDEX:ENC:FNLEN:ENCODED_FILENAME_AND_PAYLOAD
  if (qrText.startsWith('V1:')) {
    const parts = qrText.split(':');
    if (parts.length < 7) return null;

    const sessionId = parts[1];
    const total = parseInt(parts[2], 10);
    const index = parseInt(parts[3], 10);
    const encodingCode = parts[4];
    const fnLen = parseInt(parts[5], 10);
    const rest = parts.slice(6).join(':');

    if (isNaN(total) || isNaN(index) || isNaN(fnLen) || !sessionId || rest.length < fnLen) {
      return null;
    }

    try {
      const encodedFilename = rest.slice(0, fnLen);
      const payload = rest.slice(fnLen);
      const filename = new TextDecoder().decode(base45ToUint8Array(encodedFilename));

      return {
        isFountain: false,
        sessionId,
        total,
        index,
        filename,
        encoding: encodingCode === '45' ? 'base45' : 'base64',
        payload
      };
    } catch (e) {
      return null;
    }
  }

  // Legacy pipe-delimited format fallback
  const parts = qrText.split('|');
  if (parts.length < 6) return null;
  
  const sessionId = parts[0];
  const total = parseInt(parts[1], 10);
  const index = parseInt(parts[2], 10);
  const filename = decodeURIComponent(parts[3]);
  const encodingCode = parts[4];
  const payload = parts.slice(5).join('|');
  
  if (isNaN(total) || isNaN(index) || !sessionId) {
    return null;
  }
  
  return {
    sessionId,
    total,
    index,
    filename,
    encoding: encodingCode === '45' ? 'base45' : 'base64',
    payload
  };
}

/**
 * Reconstructs the compressed data and decompresses it back.
 */
export function reconstructData(orderedPayloads, encoding) {
  const fullPayload = orderedPayloads.join('');
  const compressedData = encoding === 'base45'
    ? base45ToUint8Array(fullPayload)
    : base64ToUint8Array(fullPayload);
  return pako.ungzip(compressedData);
}
